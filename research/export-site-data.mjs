// research/export-site-data.mjs — copy the numbers the site shows from research/closed-market.json into
// web/measured-data.js. Field picks only, no arithmetic, so the page always matches the JSON.
//   node research/export-site-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const r = JSON.parse(readFileSync(join(HERE, "closed-market.json"), "utf8"));
const c = r.activity.census, o = r.activity.otherQuotedSample, d = r.drift.primaryVenues, n = r.drift.vsNyseClose, f = r.pools.feeOpenVsClosed;
const w = r.worstEpisodes[0];

const data = {
  generated: r.generated,
  window: { from: r.window.from, to: r.window.to, fromBlock: r.window.fromBlock, toBlock: r.window.toBlock, days: r.window.days,
    closedTimePct: r.window.closedTimePct, closedPeriods: r.window.closedPeriods, weekendHolidayPeriods: r.window.weekendHolidayPeriods },
  stocks: r.identification.counted,
  pools: { ever: r.pools.everInitialized, dynamicAll: r.pools.dynamicFeeAll, censusActive: r.pools.census.activeInWindow },
  census: { swaps: c.swaps, swapsClosedPct: c.swapsClosedPct, usd: c.usd, usdClosed: c.usdClosed, usdClosedPct: c.usdClosedPct,
    hooklessUsdClosedPct: c.hooklessPoolsOnly.usdClosedPct },
  other: { estSwaps: o.estSwaps, estSwapsClosedPct: o.estSwapsClosedPct, sampledPct: o.sampledPct },
  drift: { stocks: d.stocks, all: d.all, weekend: d.weekendHoliday, weeknight: d.weeknight,
    histWeeknight: d.histogramWeeknight, histWeekend: d.histogramWeekend,
    nyseMedianGapPct: d.nyseBaseline.medianNyseGapPct, nyseP90GapPct: d.nyseBaseline.p90NyseGapPct },
  vsNyse: { preCloseMedianPct: n.controlLast30MinBeforeClose.medianPct, closedMedianPct: n.all.medianPct, closedP90Pct: n.all.p90Pct, weekendP90Pct: n.weekendHoliday.p90Pct },
  fees: { openPct: f.volumeWeightedFee.openPct, closedPct: f.volumeWeightedFee.closedPct },
  worst: { ticker: w.ticker, periodKind: w.periodKind, closedFrom: w.closedFrom, closedTo: w.closedTo, maxDevPct: w.maxDevPct, anchorUsd: w.anchorUsd, worstUsd: w.worstUsd,
    worstAt: w.worstAt, nyseLastClose: w.nyseLastClose, usdInPeriod: w.usdInPeriod },
};

writeFileSync(join(HERE, "..", "web", "measured-data.js"),
  `// Generated by research/export-site-data.mjs from research/closed-market.json — do not hand-edit.\n` +
  `export const MEASURED = ${JSON.stringify(data, null, 2)};\n`);
console.log("wrote web/measured-data.js");
